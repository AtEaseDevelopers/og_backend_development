<?php

namespace App\Domains\Commission\Actions;

use App\Domains\Commission\Models\CommissionBatch;
use App\Domains\Commission\Models\CommissionBatchCsn;
use App\Domains\Consignment\Models\ConsignmentNote;
use App\Domains\Commission\Models\CommissionLineItem;
use App\Domains\Commission\Models\CommissionSlip;
use App\Domains\Dispatch\Models\DeliveryOrder;
use App\Domains\MasterData\Models\Branch;
use App\Enums\DeliveryOrderStatus;
use App\Enums\DocumentType;
use App\Models\User;
use App\Services\DocumentNumberingService;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\DB;
use InvalidArgumentException;

class GenerateCommissionBatch
{
    public function __construct(
        private DocumentNumberingService $numbering,
        private ResolveCommissionShares $shares,
    ) {}

    /**
     * The month's batch of the branch (user, 21 Oct 2026): only returned CSNs earn commission. It takes every CSN of
     * the branch returned on or before the cutoff date (default the month's last day) that is not in another batch;
     * a CSN not returned yet is left for a later batch. Each CSN's delivery legs are shared as ResolveCommissionShares
     * says (80% pool, pickup fixed amount, the rest split). A draft batch is rebuilt each time.
     */
    public function execute(Branch $branch, string $month, User $actor, ?Carbon $cutoff = null): CommissionBatch
    {
        if (! preg_match('/^\d{4}-\d{2}$/', $month)) {
            throw new InvalidArgumentException('Month must be YYYY-MM.');
        }

        $start = Carbon::createFromFormat('Y-m', $month)->startOfMonth();
        $cutoff = ($cutoff ?? $start->copy()->endOfMonth())->copy();

        return DB::transaction(function () use ($branch, $month, $actor, $cutoff) {
            $batch = CommissionBatch::query()->firstOrNew([
                'source_branch_id' => $branch->id,
                'month' => $month,
            ]);

            if ($batch->exists && $batch->status === 'confirmed') {
                throw new InvalidArgumentException('Commission batch for '.$month.' is already confirmed/locked.');
            }

            if (! $batch->exists) {
                $batch->number = $this->numbering->next($branch, DocumentType::CommissionBatch);
                $batch->status = 'draft';
            }

            // the branch's company: the Commission lists show a company's batches and slips
            $companyId = $batch->company_id ?? $branch->defaultCompany()?->id;

            $batch->fill([
                'company_id' => $companyId,
                'cutoff_date' => $cutoff->toDateString(),
                'notes' => 'Generated by '.$actor->name.' at '.now()->toDateTimeString().' · CSNs returned on or before '.$cutoff->format('d/m/Y'),
            ])->save();

            // Rebuild draft slips and the batch's CSN list
            $batch->slips()->each(function (CommissionSlip $slip) {
                $slip->lines()->delete();
                $slip->adjustments()->delete();
                $slip->purchaseOrder()?->delete();
                $slip->delete();
            });
            $batch->csns()->delete();

            // the branch's CSNs returned on or before the cutoff and not in another batch
            $csns = ConsignmentNote::query()
                ->where('source_branch_id', $branch->id)
                ->whereHas('returnedCsn', fn ($q) => $q->where('returned_at', '<=', $cutoff->copy()->endOfDay()))
                ->whereNotIn('id', CommissionBatchCsn::query()->select('consignment_note_id'))
                ->with('returnedCsn')
                ->orderBy('id')
                ->get();

            /** @var array<int, array{slip: CommissionSlip, psi: float, pso: float}> $slipMap */
            $slipMap = [];

            // one PO (slip) per lorry (user, 21 Oct 2026): its drivers' commission inside it; a leg without a
            // lorry gets its driver's own slip
            $slipKey = fn (?int $driverId, ?int $lorryId) => $lorryId ? 'lorry:'.$lorryId : 'driver:'.$driverId;

            $ensureSlip = function (?int $driverId, ?int $lorryId) use (&$slipMap, $batch, $branch, $companyId, $slipKey) {
                if (! $driverId) {
                    return null;
                }
                $key = $slipKey($driverId, $lorryId);
                if (! isset($slipMap[$key])) {
                    $slip = CommissionSlip::query()->create([
                        'number' => $this->numbering->next($branch, DocumentType::CommissionSlip),
                        'company_id' => $companyId,
                        'commission_batch_id' => $batch->id,
                        'source_branch_id' => $branch->id,
                        'driver_id' => $lorryId ? null : $driverId,
                        'lorry_id' => $lorryId,
                        'system_amount' => 0,
                        'final_amount' => 0,
                        'psi_amount' => 0,
                        'pso_amount' => 0,
                        'deductions' => 0,
                        'status' => 'draft',
                    ]);
                    $slipMap[$key] = ['slip' => $slip, 'psi' => 0.0, 'pso' => 0.0];
                }

                return $slipMap[$key]['slip'];
            };

            foreach ($csns as $csn) {
                $amount = 0.0;
                $orders = DeliveryOrder::query()
                    ->with(['consignmentNote.returnedCsn', 'lorry', 'driver', 'failedDelivery', 'subsheets'])
                    ->where('consignment_note_id', $csn->id)
                    ->whereIn('status', [
                        DeliveryOrderStatus::Delivered->value,
                        DeliveryOrderStatus::Failed->value,
                        DeliveryOrderStatus::Reassigned->value,
                    ])
                    ->orderBy('id')
                    ->get();

                foreach ($orders as $do) {
                    foreach ($this->shares->execute($do) as $share) {
                        $slip = $ensureSlip($share['driver_id'], $share['lorry_id']);
                        if (! $slip) {
                            continue;
                        }

                        CommissionLineItem::query()->create([
                            'commission_slip_id' => $slip->id,
                            'delivery_order_id' => $do->id,
                            'consignment_note_id' => $do->consignment_note_id,
                            'driver_id' => $share['driver_id'],
                            'lorry_id' => $share['lorry_id'],
                            'amount' => $share['amount'],
                            // the calculated amount; admin may change amount per CSN (lorry / job sheet page)
                            'system_amount' => $share['amount'],
                            'split_percent' => $share['split_percent'],
                            'line_type' => $share['line_type'],
                            // returned: earned
                            'is_eligible' => true,
                            'is_hidden' => false,
                            'is_carry_forward' => false,
                            'notes' => $share['notes'],
                        ]);

                        $amount += (float) $share['amount'];

                        if ($share['line_type'] === 'psi') {
                            $slipMap[$slipKey($share['driver_id'], $share['lorry_id'])]['psi'] += $share['amount'];
                        }
                        if ($share['line_type'] === 'pso') {
                            $slipMap[$slipKey($share['driver_id'], $share['lorry_id'])]['pso'] += $share['amount'];
                        }
                    }
                }

                CommissionBatchCsn::query()->create([
                    'commission_batch_id' => $batch->id,
                    'consignment_note_id' => $csn->id,
                    'returned_at' => $csn->returnedCsn?->returned_at,
                    'amount' => round($amount, 2),
                ]);
            }

            // lines of these CSNs held back by an earlier batch (not returned then) are settled by this one
            if ($csns->isNotEmpty()) {
                CommissionLineItem::query()
                    ->whereIn('consignment_note_id', $csns->pluck('id'))
                    ->where('is_carry_forward', true)
                    ->whereHas('slip', fn ($q) => $q->where('commission_batch_id', '!=', $batch->id))
                    ->update(['is_carry_forward' => false]);
            }

            foreach ($slipMap as $entry) {
                /** @var CommissionSlip $slip */
                $slip = $entry['slip'];
                $system = (float) $slip->lines()->where('is_hidden', false)->sum('amount');
                $eligible = (float) $slip->lines()
                    ->where('is_hidden', false)
                    ->where('is_eligible', true)
                    ->sum('amount');

                $slip->update([
                    'system_amount' => $system,
                    'final_amount' => $eligible,
                    'psi_amount' => $entry['psi'],
                    'pso_amount' => $entry['pso'],
                    'deductions' => 0,
                ]);
            }

            return $batch->fresh(['slips.lines', 'slips.driver', 'sourceBranch', 'csns']);
        });
    }
}
